// newDatabase returns a test database with two keys and four hosts that
// cover the cases of the sync: key, no key, options and an invalid entry.
func newDatabase(t *testing.T) string {
	t.Helper()
	path := vaulttest.NewDatabase(t)

	err := vaulttest.Modify(path, func(v *vault.Vault) error {
		for _, name := range []string{"dd-key", "spare"} {
			pair, err := sshkey.Generate(sshkey.TypeEd25519, 0, name)
			if err != nil {
				return err
			}
			if err := v.AddKey(vault.NewKey{Name: name, Type: pair.Type, PublicKey: pair.PublicLine,
				Fingerprint: pair.Fingerprint, PrivatePEM: pair.PrivatePEM}); err != nil {
				return err
			}
		}

		hosts := []vault.NewHost{
			{Name: "dd.lan", Address: "dd.lan", User: "max", KeyName: "dd-key"},
			{Name: "web02", Address: "10.0.0.2", Port: 2222, User: "deploy", Options: []string{"ServerAliveInterval=30"}},
		}
		for _, host := range hosts {
			if err := v.AddHost(host); err != nil {
				return err
			}
		}
		return nil
	})
	if err != nil {
		t.Fatalf("cannot prepare test database: %v", err)
	}
	return path
}

func runSync(t *testing.T, dbPath, defaultDir string, args ...string) string {
	t.Helper()
	var out bytes.Buffer
	open := func() (*vault.Vault, error) { return vaulttest.Open(dbPath) }
	if err := Run(args, open, defaultDir, &out); err != nil {
		t.Fatalf("sync failed: %v\n%s", err, out.String())
	}
	return out.String()
}

func TestSyncWritesKeysAndConfig(t *testing.T) {
	dbPath := newDatabase(t)
	dir := filepath.Join(t.TempDir(), ".ssh")

	runSync(t, dbPath, dir)

	// The private key on disk must be usable by ssh as is.
	privatePEM, err := os.ReadFile(filepath.Join(dir, "dd-key"))
	if err != nil {
		t.Fatalf("private key not written: %v", err)
	}
	if _, err := ssh.ParsePrivateKey(privatePEM); err != nil {
		t.Fatalf("written private key is not valid: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "spare.pub")); err != nil {
		t.Fatalf("keys without hosts must be written too: %v", err)
	}

	hostsConfig, err := os.ReadFile(filepath.Join(dir, zzhConfigName))
	if err != nil {
		t.Fatalf("zzh_config not written: %v", err)
	}
	text := string(hostsConfig)

	expected := []string{
		"Host dd.lan\n    HostName dd.lan\n    User max\n    IdentityFile ~/.ssh/dd-key\n    IdentitiesOnly yes\n",
		"Host web02\n    HostName 10.0.0.2\n    User deploy\n    Port 2222\n    ServerAliveInterval 30\n",
	}
	for _, block := range expected {
		if !strings.Contains(text, block) {
			t.Errorf("missing block:\n%s\nin:\n%s", block, text)
		}
	}

	// Without a previous config, a minimal one including zzh_config is
	// created.
	userConfig, err := os.ReadFile(filepath.Join(dir, "config"))
	if err != nil || !strings.Contains(string(userConfig), "Include zzh_config\n") {
		t.Fatalf("config must include zzh_config: %q (%v)", userConfig, err)
	}
}

// The user's own config is kept: only the Include line is added at the top,
// once, and the original is backed up as config_1.bkp.
func TestSyncIntegratesExistingConfig(t *testing.T) {
	dbPath := newDatabase(t)
	dir := t.TempDir()

	original := []byte("Host 10.99.42.1\r\n  HostName 10.99.42.1\r\n  User max\r\n")
	if err := os.WriteFile(filepath.Join(dir, "config"), original, 0o600); err != nil {
		t.Fatalf("cannot write user config: %v", err)
	}

	runSync(t, dbPath, dir)

	updated, err := os.ReadFile(filepath.Join(dir, "config"))
	if err != nil {
		t.Fatalf("cannot read config: %v", err)
	}
	// Include first, user content untouched after it, CRLF preserved.
	if !strings.HasPrefix(string(updated), "# Hosts from KeePass, generated by \"zzh sync out\".\r\nInclude zzh_config\r\n\r\n") ||
		!bytes.HasSuffix(updated, original) {
		t.Fatalf("unexpected config:\n%q", updated)
	}

	backup, err := os.ReadFile(filepath.Join(dir, "config_1.bkp"))
	if err != nil || !bytes.Equal(backup, original) {
		t.Fatalf("the original config must be kept as config_1.bkp: %v", err)
	}

	// A second sync adds nothing: the Include is already there and the
	// other files are identical.
	out := runSync(t, dbPath, dir)
	if !strings.Contains(out, "0 written") {
		t.Fatalf("a repeated sync must not change anything:\n%s", out)
	}
	if _, err := os.Stat(filepath.Join(dir, "config_2.bkp")); err == nil {
		t.Fatalf("no new backup must be created")
	}
}

// Hand edits to zzh_config are replaced, but kept with the next number.
func TestSyncBacksUpChangedZzhConfig(t *testing.T) {
	dbPath := newDatabase(t)
	dir := t.TempDir()
	runSync(t, dbPath, dir)

	path := filepath.Join(dir, zzhConfigName)
	for n := 1; n <= 2; n++ {
		if err := os.WriteFile(path, []byte("edited by hand\n"), 0o600); err != nil {
			t.Fatalf("cannot edit zzh_config: %v", err)
		}
		runSync(t, dbPath, dir)

		backup := path + "_" + string(rune('0'+n)) + ".bkp"
		if content, err := os.ReadFile(backup); err != nil || string(content) != "edited by hand\n" {
			t.Fatalf("expected %s with the edited content: %v", backup, err)
		}
	}
}

func TestIncludesZzhConfig(t *testing.T) {
	present := []string{
		"Include zzh_config\n",
		"  include ~/.ssh/zzh_config\n",
		"Include=\"C:/Users/max/.ssh/zzh_config\"\r\n",
		"Include other.conf zzh_config\n",
	}
	for _, content := range present {
		if !includesZzhConfig([]byte(content)) {
			t.Errorf("not detected: %q", content)
		}
	}

	absent := []string{
		"Host zzh_config\n",
		"# Include zzh_config\n",
		"Include other.conf\n",
	}
	for _, content := range absent {
		if includesZzhConfig([]byte(content)) {
			t.Errorf("wrongly detected: %q", content)
		}
	}
}

func TestSyncDryRunChangesNothing(t *testing.T) {
	dbPath := newDatabase(t)
	dir := filepath.Join(t.TempDir(), ".ssh")

	out := runSync(t, dbPath, dir, "--dry-run")
	if !strings.Contains(out, "Dry run") || !strings.Contains(out, "write") {
		t.Fatalf("dry run must report the planned actions:\n%s", out)
	}
	if _, err := os.Stat(dir); err == nil {
		t.Fatalf("dry run must not even create the directory")
	}
}

func TestSyncCustomDirUsesAbsolutePaths(t *testing.T) {
	dbPath := newDatabase(t)
	defaultDir := filepath.Join(t.TempDir(), "never-used")
	target := filepath.Join(t.TempDir(), "with space")

	runSync(t, dbPath, defaultDir, "--dir", target)

	hostsConfig, err := os.ReadFile(filepath.Join(target, zzhConfigName))
	if err != nil {
		t.Fatalf("zzh_config not written in --dir: %v", err)
	}
	expected := `IdentityFile "` + filepath.ToSlash(filepath.Join(target, "dd-key")) + `"`
	if !strings.Contains(string(hostsConfig), expected) {
		t.Fatalf("expected %s in:\n%s", expected, hostsConfig)
	}

	// Outside ~/.ssh a relative Include would be resolved against ~/.ssh,
	// so the path must be absolute.
	userConfig, err := os.ReadFile(filepath.Join(target, "config"))
	expectedInclude := `Include "` + filepath.ToSlash(filepath.Join(target, zzhConfigName)) + `"`
	if err != nil || !strings.Contains(string(userConfig), expectedInclude) {
		t.Fatalf("expected %s in:\n%s (%v)", expectedInclude, userConfig, err)
	}
	if _, err := os.Stat(defaultDir); err == nil {
		t.Fatalf("the default directory must not be touched when --dir is given")
	}
}

func TestBuildConfigWarnings(t *testing.T) {
	hosts := []vault.Host{
		{Name: "broken", Problem: "the URL field is empty"},
		{Name: "orphan", Address: "o.lan", KeyID: "DEADBEEF"},
	}

	config, warnings := buildConfig(hosts, map[string]string{})

	if strings.Contains(string(config), "Host broken") {
		t.Errorf("invalid hosts must be skipped")
	}
	if !strings.Contains(string(config), "Host orphan") || strings.Contains(string(config), "IdentityFile") {
		t.Errorf("a host with a missing key must be written without IdentityFile:\n%s", config)
	}
	if len(warnings) != 2 {
		t.Errorf("expected 2 warnings, got %q", warnings)
	}
}

func TestRunRejectsArguments(t *testing.T) {
	var out bytes.Buffer
	open := func() (*vault.Vault, error) {
		t.Fatalf("the database must not be opened for invalid arguments")
		return nil, nil
	}
	for _, args := range [][]string{{"extra"}, {"--dir"}, {"--unknown"}} {
		if err := Run(args, open, t.TempDir(), &out); err == nil {
			t.Errorf("%q: expected an error", args)
		}
	}
}

// Private files must be readable by the owner only, otherwise ssh ignores
// the key ("UNPROTECTED PRIVATE KEY FILE"). On Windows this means no
// inherited ACL entries; elsewhere it means mode 0600.
func TestPrivateFilesAreOwnerOnly(t *testing.T) {
	dbPath := newDatabase(t)
	dir := filepath.Join(t.TempDir(), ".ssh")
	runSync(t, dbPath, dir)

	for _, name := range []string{"dd-key", "config", zzhConfigName} {
		path := filepath.Join(dir, name)

		if runtime.GOOS == "windows" {
			output, err := exec.Command("icacls", path).CombinedOutput()
			if err != nil {
				t.Fatalf("icacls failed: %v", err)
			}
			if strings.Contains(string(output), "(I)") {
				t.Errorf("%s still has inherited permissions:\n%s", name, output)
			}
			continue
		}

		info, err := os.Stat(path)
		if err != nil {
			t.Fatalf("cannot stat %s: %v", name, err)
		}
		if info.Mode().Perm() != 0o600 {
			t.Errorf("%s has mode %v, expected 0600", name, info.Mode().Perm())
		}
	}
}

func TestBuildConfigWritesAliases(t *testing.T) {
	hosts := []vault.Host{{Name: "centauri", Aliases: []string{"c", "centauri.lan"}, Address: "192.168.3.1"}}
	config, _ := buildConfig(hosts, map[string]string{})
	if !strings.Contains(string(config), "\nHost centauri c centauri.lan\n    HostName 192.168.3.1\n") {
		t.Fatalf("aliases must be on the Host line:\n%s", config)
	}
}
